# 全部通过、单对象超阈值（准时出数与同批口径冲突）、缺少样本。
# ---------------------------------------------------------------------------
def _check_item(rule_id: str, sample: float | None) -> dict:
    base = next(item for item in QUALITY_SAMPLES if item["规则编号"] == rule_id)
    return {
        "监控对象": base["监控对象"],
        "检查项": base["检查项"],
        "阈值上限": base["阈值上限"],
        "阈值下限": base["阈值下限"],
        "样本值": sample,
    }


